/** سبب فشل الذكاء الاصطناعي بلغة الأستاذ، من رسالة الخطأ التقنية (تبقى الرسالة الأصلية في سجل المهام) */
export function aiFailureReason(err: unknown): string {
  const m = err instanceof Error ? `${err.name} ${err.message}` : String(err)
  if (/insufficient_quota/.test(m)) return 'رصيد حساب الذكاء الاصطناعي (OpenAI) منتهٍ: يجب شحنه ثم إعادة المحاولة.'
  if (/HTTP 40[13]\b/.test(m)) return 'مفتاح الذكاء الاصطناعي مرفوض: يجب تحديثه على الخادم.'
  if (/HTTP 429/.test(m)) return 'خدمة الذكاء الاصطناعي مزدحمة الآن: أعد المحاولة بعد دقائق.'
  if (/truncated/.test(m)) return 'الاختبار المطلوب أطول مما يسمح به الردّ الواحد: قلّل عدد الأسئلة.'
  if (/timeout|abort/i.test(m)) return 'انتهت مهلة انتظار الذكاء الاصطناعي: أعد المحاولة بعدد أسئلة أقل أو مصادر أقل.'
  if (/HTTP 5\d\d/.test(m)) return 'خدمة الذكاء الاصطناعي متعطّلة مؤقتاً: أعد المحاولة لاحقاً.'
  if (/JSON/.test(m)) return 'ردّ الذكاء الاصطناعي لم يكن بالصيغة المطلوبة: أعد المحاولة.'
  if (/refused|content filter/.test(m)) return 'رفض الذكاء الاصطناعي الطلب: راجع مضمون المصادر.'
  return 'خطأ غير متوقع أثناء التوليد: أعد المحاولة، وإن تكرّر راجع صفحة الذكاء الاصطناعي في الإدارة.'
}
