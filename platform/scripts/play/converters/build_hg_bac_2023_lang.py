def essay(qid, title, task, para_doc, sections, skill, page_ref):
    """sections: list of (section_label, eid_prefix, [(points, indicator)], model_points_or_None)."""
    elements = []
    for sec, pre, lines, model in sections:
        for k, (pts, ind) in enumerate(lines, 1):
            eid = f"{qid}-{pre}{k}" if len(lines) > 1 else f"{qid}-{pre}"
            label = sec if len(lines) == 1 else f"{sec} — العنصر {k} من {len(lines)}"
            elements.append(el(eid, label, pts))
            spec = {"task": task, "paragraph_doc": para_doc, "section": sec, "criterion": label, "indicator": ind}
            if model:
                spec["model_points"] = model
                spec["accepts_other_correct_answers"] = True
            deferred(sid(), qid, eid, "essay_builder", f"{title} — {label}", spec,
                     {"rubric": ind, "points": pts, "model_ref": page_ref},
                     f"سلّم التنقيط ({sec}): {ind} — {pts} ن.", pts, skill)
    return elements


