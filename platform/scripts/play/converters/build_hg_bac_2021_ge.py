def comment(eid: str, false_statements: list[str], prompt: str) -> dict:
    """comment_step (hg_record.py) دون سطر العنوان الذي يسبق أوّل ❖ في official_answer: comment_step يعدّه عبارة صحيحة."""
    e = elements(REC)[eid]
    assert e['answer_type'] == 'alternatives', eid
    _, sep, body = e['official_answer'].partition('❖')
    assert sep, eid
    trail = lambda x: re.sub(r'[\s.…]+$', '', x.strip())
    rights = [trail(x) for x in body.split('❖') if x.strip()]
    opts = rights + [trail(x) for x in false_statements]
    assert 2 <= len(rights) <= 5 and 2 <= len(false_statements) <= 3 and len(set(opts)) == len(opts), eid
    expl = 'التعليق في الإجابة النموذجيّة: ' + ' — '.join(rights) + '.'
    return multi(prompt, opts, list(range(len(rights))), expl, e['marks'], 'geo.data')


