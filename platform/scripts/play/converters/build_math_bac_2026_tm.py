MATH_RE = re.compile(r"\$\$([^$]+)\$\$|\$([^$\n]+)\$")  # = rich-text.tsx / text-dir.ts


def _dir(s):
    """= textDir() in src/components/play/text-dir.ts (ignores what is between $…$)"""
    plain = MATH_RE.sub(" ", s)
    ar = len(re.findall("[؀-ۿ]", plain))
    la = len(re.findall("[A-Za-z]", plain))
    return ar, la, ("ltr" if la > ar else "rtl")


def _norm(s):
    s = unicodedata.normalize("NFKC", s)
    s = re.sub("[ً-ْٰـ]", "", s)
    s = re.sub("[أإآٱ]", "ا", s).replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    s = "".join(c if (c.isalnum() or c.isspace()) and c != "_" else " " for c in s)
    return re.sub(r"\s+", " ", s.lower()).strip()


_PTS = [{"x": 0.37, "n": 3, "k": 2, "α": -1.65, "m": 0.4, "q": 1.7, "r": 2.3},
        {"x": 1.3, "n": 5, "k": 4, "α": -1.62, "m": 1.8, "q": 0.6, "r": -0.7}]


def _value(opt):
    """numeric value(s) of a purely numeric/algebraic option «$…$», or None if not evaluable.
    «name=…=expr» (u_n=…, P(A)=…, f'(x)=…, (T):y=…) → value of the last expression; an equation whose left side is itself an
    expression («n^2/(n+10)^2=1/4») → value of left − right."""
    s = opt.strip()
    if s.count("$") != 2 or not (s.startswith("$") and s.endswith("$")):
        return None
    s = re.sub(r"^\(T\):", "", s[1:-1])
    if re.search(r"[؀-ۿ]|\\(in|le|ge|cup|cap|equiv|overline|mathbb|lim|int|simeq|approx|overset|mapsto|vec|overrightarrow|Delta)\b|[;\[\]<>|:]|PGCD|PPCM|u\.a", s):
        return None
    parts = s.split("=")
    if len(parts) == 2:
        lv, rv = _expr_value(parts[0]), _expr_value(parts[1])
        if lv is not None and rv is not None:
            return tuple(x - y for x, y in zip(lv, rv))
    return _expr_value(parts[-1])


def _expr_value(s):
    for a, b in [(r"\left", ""), (r"\right", ""), (r"\times", "*"), (r"\cdot", "*"), (r"\,", ""), (r"\infty", "oo"), (r"\alpha", "α"), (r"\dfrac", r"\frac")]:
        s = s.replace(a, b)
    s = re.sub(r"([AC])_(?:\{(\d+)\}|(\d))\^(?:\{(\d+)\}|(\d))",
               lambda m_: f"{'perm' if m_.group(1) == 'A' else 'comb'}({m_.group(2) or m_.group(3)},{m_.group(4) or m_.group(5)})", s)
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r"\\frac\{([^{}]*)\}\{([^{}]*)\}", r"((\1)/(\2))", s)
        s = re.sub(r"\\sqrt\{([^{}]*)\}", r"sqrt(\1)", s)
        s = re.sub(r"\^\{([^{}]*)\}", r"^(\1)", s)
    s = re.sub(r"\\ln\s*", "log ", s)
    if "\\" in s or "{" in s or "}" in s or "_" in s or "'" in s:
        return None
    toks = [t for t in re.findall(r"\d+(?:\.\d+)?|log|sqrt|exp|perm|comb|oo|[a-zα]|[-+*/^(),]|\s+", s) if not t.isspace()]
    if re.sub(r"\s+", "", "".join(toks)) != re.sub(r"\s+", "", s):
        return None
    out, i = [], 0
    funcs = {"log", "sqrt", "exp", "perm", "comb"}
    atom = lambda t: re.fullmatch(r"\d+(?:\.\d+)?|oo|[a-zα]", t) is not None
    while i < len(toks):
        t = toks[i]
        if t in funcs and i + 1 < len(toks) and atom(toks[i + 1]):
            out.append(f"{t}({toks[i + 1]})")
            i += 2
            continue
        out.append(t)
        i += 1
    expr = ""
    for j, t in enumerate(out):
        if j and (atom(out[j - 1]) or out[j - 1] == ")" or out[j - 1].endswith(")")) and (atom(t) or t == "(" or t.split("(")[0] in funcs):
            expr += "*"
        expr += t
    expr = expr.replace("^", "**")
    vals = []
    for p in _PTS:
        env = {"log": math.log, "sqrt": math.sqrt, "exp": math.exp, "perm": math.perm, "comb": math.comb, "e": math.e, "oo": float("inf"), **p}
        try:
            vals.append(float(eval(expr, {"__builtins__": {}}, env)))
        except Exception:
            return None
    return tuple(vals)


def _same(a, b):
    return all((x == y) if (math.isinf(x) or math.isinf(y)) else abs(x - y) < 1e-9 * max(1, abs(x)) for x, y in zip(a, b))


def _check(total=20):
    els = {e["id"]: e for qq in Q for e in qq["rubric_elements"]}
    assert len(els) == sum(len(qq["rubric_elements"]) for qq in Q), "duplicate element ids"
    assert len({qq["id"] for qq in Q}) == len(Q), "duplicate question ids"
    for qq in Q:
        assert abs(sum(e["max_points"] for e in qq["rubric_elements"]) - qq["rubric_total"]) < 1e-9, qq["id"]
        assert qq["verbatim_text"] and qq["verbatim_text"].strip() == qq["verbatim_text"], qq["id"]
        assert "$" not in qq["part"], (qq["id"], "no $ in part titles")
        for e in qq["rubric_elements"]:
            assert "$" not in e["label"], (e["id"], "labels are plain text")
        for d in qq["documents"]:
            assert "$" not in d["caption"], (d["id"], "no $ in captions")
            if d.get("media"):
                assert (ROOT / "public" / d["media"]["local_path"].lstrip("/")).exists(), d["media"]["local_path"]
    assert abs(sum(qq["rubric_total"] for qq in Q) - total) < 1e-9, sum(qq["rubric_total"] for qq in Q)
    assert abs(sum(s["points"] for s in S) - total) < 1e-9, sum(s["points"] for s in S)
    got, flips, latex, compared = {}, [], [], 0
    for qq in Q:
        latex += [qq["verbatim_text"], *[d["text"] for d in qq["documents"] if d.get("text")]]
    for s in S:
        p, a, t = s["payload"], s["answer"], s["type"]
        assert s["skill_id"] in SKILLS, (s["id"], s["skill_id"])
        assert s["rubric_element_id"] in els and s["rubric_element_id"].startswith(s["source_question_id"] + "-"), s["id"]
        assert s["points"] > 0 and abs(s["points"] * 4 - round(s["points"] * 4)) < 1e-9, (s["id"], "points not a multiple of 0.25")
        assert s["explanation"].strip() and s["prompt"].strip(), s["id"]
        got[s["rubric_element_id"]] = got.get(s["rubric_element_id"], 0) + s["points"]
        shown = [s["prompt"], s["explanation"]]
        if t == "mcq":
            assert 3 <= len(p["options"]) <= 4 and a["correct"] == 0, (s["id"], "mcq: 3–4 options, right one first before shuffling")
            v0 = _value(p["options"][0])
            for o in p["options"][1:]:
                v = _value(o)
                if v0 is not None and v is not None:
                    compared += 1
                    assert not _same(v0, v), (s["id"], "distractor equal in value to the right answer", p["options"][0], o)
        if t in ("mcq", "multi"):
            assert len(set(p["options"])) == len(p["options"]), (s["id"], "duplicate options")
            shown += p["options"]
        if t == "multi":
            assert len(p["options"]) >= 3 and 0 < len(a["correct"]) < len(p["options"]), s["id"]
            rights = [_value(p["options"][i]) for i in a["correct"]]
            for j, o in enumerate(p["options"]):
                v = _value(o)
                if j in a["correct"] or v is None:
                    continue
                for rv in rights:
                    if rv is not None:
                        compared += 1
                        assert not _same(rv, v), (s["id"], "multi: wrong option equal in value to a right one", o)
        if t == "numeric":
            assert isinstance(a["value"], (int, float)) and a["tolerance"] >= 0, s["id"]
        if t in ("essay_builder", "table_fill", "variation_table", "function_plot"):
            assert s["review_status"] == "needs_engine_support", s["id"]
            latex += [s["prompt"]]
        else:
            assert s["review_status"] == "needs_human_review", s["id"]
            latex += shown
            for x in shown:  # النصوص الّتي يكتبها المحوِّل يجب أن تُعرض من اليمين إلى اليسار
                ar, la, d = _dir(x)
                if ar and d == "ltr":
                    flips.append((s["id"], ar, la, x))
    for eid, e in els.items():
        assert abs(got.get(eid, 0) - e["max_points"]) < 1e-9, (eid, got.get(eid), e["max_points"])
    assert len({s["id"] for s in S}) == len(S), "duplicate step ids"
    fps = [(_norm(s["prompt"]), json.dumps(s["payload"], ensure_ascii=False)) for s in S]
    assert len(set(fps)) == len(fps), "duplicate step content"
    assert not flips, "converter-written strings that text-dir.ts would render LTR:\n" + "\n".join(map(str, flips))
    for qq in Q:
        for t in [qq["verbatim_text"], *[d["text"] for d in qq["documents"] if d.get("text")]]:
            assert _dir(t)[2] == "rtl", (qq["id"], "verbatim rendered LTR", t[:60])
    # KaTeX: every $…$ must parse (same library as the renderer)
    spans = sorted({(m_.group(1) or m_.group(2)).strip() for x in latex for m_ in MATH_RE.finditer(x)})
    js = ("const k=require(process.argv[1]);let bad=0;for(const t of JSON.parse(require('fs').readFileSync(0,'utf8'))){"
          "try{k.renderToString(t,{throwOnError:true,strict:'error'})}catch(e){bad++;console.log('KATEX',t,e.message)}}process.exit(bad?1:0)")
    katex = ROOT / "node_modules" / "katex"
    if katex.exists():
        r = subprocess.run(["node", "-e", js, str(katex)], input=json.dumps(spans), capture_output=True, text=True)
        assert r.returncode == 0, r.stdout + r.stderr
    else:
        print("warning: node_modules/katex missing — LaTeX not parsed")
    return spans, compared


