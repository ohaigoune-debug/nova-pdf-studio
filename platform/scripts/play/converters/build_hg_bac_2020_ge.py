def d(eid, ds, skill, kind, name=None):
    return [definition_step(REC, eid, ds, skill, kind, name)]


def t(eid, distractors, asks='date', item=None, src=None):
    """table_step؛ item = نصّ الخانة كما في الورقة إن خالف رسمُه السجلّ. كلّ مشتّت يرد حرفيًّا في التصحيح، أو (src) تاريخ من
    التصحيح نفسه مكتوب بصيغة الجدول: src = {المشتّت: نصّه في التصحيح}."""
    src = src or {}
    for x in distractors:
        assert (src.get(x) or x) in _OFFICIAL, (eid, x)
    s = table_step(REC, eid, distractors, asks=asks)
    if item:
        old = E[eid]['item'].strip()
        s['prompt'], s['explanation'] = s['prompt'].replace(old, item), s['explanation'].replace(old, item)
    return [s]


def statements(eid):
    """عبارات ❖ في جواب التصحيح بلا السطر التمهيديّ الذي يسبق أوّل ❖."""
    return [_TR.sub('', x.strip()) for x in E[eid]['official_answer'].split('❖')[1:] if x.strip()]


def comment_all(eid, false_statements, prompt, skill='geo.data'):
    """comment_step بلا السطر التمهيديّ: الصحيح = عبارات التصحيح، والخاطئ تنقضه أرقام الجدول المطبوع."""
    e = E[eid]
    assert e['answer_type'] == 'alternatives', eid
    rights = statements(eid)
    opts = rights + [_TR.sub('', x.strip()) for x in false_statements]
    assert 2 <= len(rights) <= 5 and 2 <= len(false_statements) <= 3 and len({_norm(o) for o in opts}) == len(opts), eid
    expl = 'التعليق في الإجابة النموذجيّة: ' + ' — '.join(rights) + '.'
    return [multi(prompt, opts, list(range(len(rights))), expl, e['marks'], skill)]


def comment_one(eid, false_statements, prompt, skill='geo.data'):
    """عنصر تعليق بعبارة رسميّة واحدة: mcq، الصحيح عبارة التصحيح، والمشتّتات عبارات تنقضها أرقام الجدول المطبوع."""
    e = E[eid]
    assert e['answer_type'] == 'alternatives', eid
    rights = statements(eid)
    assert len(rights) == 1 and len(false_statements) == 3, eid
    opts = rights + [_TR.sub('', x.strip()) for x in false_statements]
    assert len({_norm(o) for o in opts}) == len(opts), eid
    return [mcq(prompt, opts, 0, f'التعليق في الإجابة النموذجيّة: {rights[0]}.', e['marks'], skill)]


