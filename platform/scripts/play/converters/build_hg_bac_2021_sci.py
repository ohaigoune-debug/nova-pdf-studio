d = lambda eid, ds, skill, kind, name=None: [definition_step(REC, eid, ds, skill, kind, name)]


def person3(eid: str, others: list[str], name: str | None = None) -> list[dict]:
    """definition_step للشخصيّات بمشتّتين (لا شخصيّة ثالثة أخرى في التصحيح): mcq بثلاثة خيارات."""
    E = elements(REC)
    e = E[eid]
    assert e['answer_type'] == 'fixed' and len(others) == 2 and eid not in others, eid
    corr_name, right = split_definition(e['official_answer'])
    name = name or corr_name
    opts = [right] + [split_definition(E[o]['official_answer'])[1] for o in others]
    assert all(opts) and len(set(opts)) == 3, eid
    return [mcq(f'من هو {name}؟', opts, 0, f'«{name}» في الإجابة النموذجيّة: {right}.', e['marks'], 'hist.figures')]


def comment_line(eid: str, wrong: list[str]) -> list[dict]:
    """عنصر تعليق بعبارة واحدة (1 ن): mcq، الصحيح عبارة التصحيح، والخاطئ عبارات تنقضها أرقام الجدول المطبوع."""
    e = elements(REC)[eid]
    assert e['answer_type'] == 'alternatives' and e['official_answer'].count('❖') == 1 and len(wrong) == 3, eid
    right = e['official_answer'].replace('❖', '').strip().rstrip('.… ')
    opts = [right, *(w.rstrip('.… ') for w in wrong)]
    assert len(set(opts)) == 4, eid
    return [mcq('أيّ العبارات التالية تصلح تعليقًا على معطيات الجدول؟', opts, 0, f'التعليق في الإجابة النموذجيّة: {right}.', e['marks'], 'geo.data')]


