"""BAC 2021 (الدورة العادية) – التاريخ والجغرافيا – علوم تجريبية، رياضيات، تقني رياضي، من سجلّ المصدر hist-bac-2021-sci.json
(نقل ChatGPT، صفّ القائمة 7). منسوخ من القدوة build_hg_bac_2020_lit.py (المعطيات وحدها تغيّرت).

    python3 scripts/play/converters/build_hg_bac_2021_sci.py content/play-exams/sets/3AS/HIST/hg-bac-2021-sci-p1.json --pdf <الموضوع.pdf>
    python3 scripts/play/shuffle_exam_set.py content/play-exams/sets/3AS/HIST/hg-bac-2021-sci-p1.json   (مرّة واحدة)
(ثمّ p2 بالطريقة نفسها). لا شكل يُقصّ من ورقة الموضوع (p1-d6 الدائرة النسبيّة من ملفّ التصحيح، لا يحيل إليها سؤال فلا تُعرض).

ما رُوجع قبل البناء:
- ورقة الموضوع صور ممسوحة بلا طبقة نصّ (pdffonts فارغ، 144 نقطة/بوصة)، وطبقة نصّ التصحيح مشوّهة الترميز: record_wordcheck.py يعلّم
  كلّ الكلمات، فقوبل كلّ سطر من الأسئلة والوثائق وكلّ رقم فيها بصورة الصفحة (300 نقطة/بوصة، وصورة الصفحة الأصلية مكبّرة بلا
  تنعيم عند الشكّ). الجداول والأرقام مطابقة؛ الفروق المؤكَّدة في FIXES، ومنها:
  * «إقليم الرّاين» (بألف، في النصّ وفي السؤال مرّتين؛ الناقل كتب «الرّين»). عنوانا المحورين في سلّم السجلّ (item) بقيا «الرّين»:
    FIXES لا تصل إلى rubric.item.
  * مرجع النصّ 1: الورقة تعرض «1950/1945» (الناقل قلبها «1945/1950»)؛ أُعيدت كما تُعرض مثل بقيّة تواريخ الورقة المنقولة بترتيب العرض.
  * «اتخذت»، «واتضح»، «ايناس»، «اطلاق»، «افريقيا» بلا شدّة/همزة كما في الورقة.
- الأجوبة الرسميّة للعناصر التفاعليّة قوبلت بصور التصحيح (ص1–5). أرقام التعليق على جدول الآسيان: 10+9+9=28 (الاتحاد الأوربي، الو.م.أ، اليابان).

قرارات المحوِّل:
- المصطلحات: mcq، المشتّتات تعريفات مصطلحات أخرى من تصحيح الورقة نفسها (الموضوعان)، تاريخ مع تاريخ وجغرافيا مع جغرافيا.
  لم يُجمع «العولمة» و«تحرير التجارة» (تعريف تحرير التجارة يصدق جزئيًّا على العولمة)، ولا «التّنمية» و«الاستثمار» (كلاهما يذكر الرفاهية).
  «المدّ الشيوعي»: تعريفه يذكر «الأفكار الشّيوعية»، فوُضع بين مشتّتاته تعريف «حلف شمال الأطلسي» الذي يذكر «المدّ الشّيوعي» (لا يدلّ اللفظ على الجواب).
- الشخصيّات: ثلاث فقط في التصحيح كلّه (ديدوش مراد، خروتشوف، ترومان) وdefinition_step يشترط ثلاثة مشتّتات: person3() المحلّي يبني
  mcq بثلاثة خيارات بالقاعدة نفسها (split_definition، الاسم كما في الورقة).
- «أكمل الجدول» (الموضوع 2): الأسطر الثلاثة تفاعليّة؛ المشتّتات أحداث/تواريخ من التصحيح غير مطبوعة في الجدول ولا في نصّ الموضوع 2
  (1960/12/11 مطبوع في النصّ فلم يُستعمل).
- التعليق على جدول الآسيان (الموضوع 2): التصحيح يقسمه ثلاثة عناصر بعبارة واحدة لكلّ منها (1 ن)؛ comment_step يشترط عبارتين صحيحتين
  على الأقلّ، فطُبّق قرار الدليل «comment lines stated in the rubric may be mcq»: mcq لكلّ عنصر، الصحيح عبارة التصحيح، والمشتّتات
  عبارات تنقضها أرقام الجدول المطبوع (مختلفة بين الخطوات الثلاث حتى لا تُستبعد بالتكرار).
- مؤجَّل لأنّ تعريف التصحيح يسمّي البند نفسه فيدلّ على الجواب، ولا مشتّت من التصحيح يحمل الاسم: «مشروع مارشال» («تقدم به جورج
  مارشال»)، «هاري ترومان» («له مبدأ حمل اسمه (مبدأ ترومان1947)»)، «مظاهرات» («ظهر ذلك في مظاهرات 1960/12/11»).
- الدائرة النسبيّة والمقالات: مؤجّلة آليًّا (source_record.py).
"""
