def listed(inds, pts=0.25):
    """one slot per listed indicator"""
    return [(ind, ind, pts, {}) for ind in inds]


def slots(n, inds, pts=0.25):
    """n slots when the correction lists more indicators than slots"""
    note = f"يُحتسب {n} عناصر صحيحة من المؤشّرات المذكورة في الإجابة النموذجيّة (تقبل كلّ الإجابات الصحيحة الأخرى)"
    return [(f"عنصر صحيح ({k} من {n})", "؛ ".join(inds), pts, {"note": note}) for k in range(1, n + 1)]


def essay(qid, part, verbatim, para, title, task, sections, intro, concl, skill, intro_pts=0.5, concl_pts=0.5):
    """sections: [(heading, items)] with items = [(criterion, indicator, points, extra)]"""
    els, lines = [], []
    def add(section, crit, ind, pts, extra):
        eid = f"{qid}-e{len(els) + 1}"
        els.append(el(eid, f"{section}: {crit}" if section.startswith("العرض") else section, pts))
        lines.append((eid, section, crit, ind, pts, extra))
    add("المقدمة", "الإشكاليّة", intro, intro_pts, {"accept": "تقبل كلّ مقدّمة وظيفيّة"})
    for i, (head, items) in enumerate(sections, 1):
        for crit, ind, pts, extra in items:
            add(f"العرض {i}- {head}", crit, ind, pts, extra)
    add("الخاتمة", "الاستنتاج", concl, concl_pts, {"accept": "تقبل كلّ خاتمة وظيفيّة"})
    q(qid, "—", part, verbatim, 4, els, [{"id": f"d-{qid}-para", "kind": "text", "caption": "العبارة", "text": fix(para)}])
    for eid, section, crit, ind, pts, extra in lines:
        deferred(sid(), qid, eid, "essay_builder", f"{title} — {section}: {crit}",
                 {"task": task, "paragraph_doc": f"d-{qid}-para", "section": section, "criterion": crit, "indicator": ind, **extra},
                 {"rubric": ind, "points": pts, "model_ref": CORR_TITLE},
                 f"سلّم التنقيط ({section}): {ind} — {pts} ن.", pts, skill)


def map_lines(qid, task, base_map, items, lines, skill, model_ref):
    """lines: (eid, criterion, answer_spec_extra, points)"""
    for eid, crit, extra, pts in lines:
        deferred(sid(), qid, eid, "map_locate", f"{task} — {crit}",
                 {"task": task, "base_map": base_map, "items": items, "criterion": crit},
                 {"rubric": crit, "points": pts, "model_ref": model_ref, **extra},
                 f"يُصحَّح على الخريطة وفق سلّم التنقيط: {crit} — {pts} ن.", pts, skill)


def text_doc(did, text, ref):
    return {"id": did, "kind": "text", "caption": "النّصّ", "text": fix(text) + "\n" + fix(ref)}


