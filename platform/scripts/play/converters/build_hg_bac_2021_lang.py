"""BAC 2021 (الدورة العادية) – التاريخ والجغرافيا – لغات أجنبية، من سجلّ المصدر hist-bac-2021-lang.json (نقل ChatGPT، صفّ القائمة 6).
منسوخ من القدوة build_hg_bac_2020_lit.py (المعطيات وحدها تغيّرت).

    python3 scripts/play/converters/build_hg_bac_2021_lang.py content/play-exams/sets/3AS/HIST/hg-bac-2021-lang-p1.json --pdf <الموضوع.pdf>
    python3 scripts/play/shuffle_exam_set.py content/play-exams/sets/3AS/HIST/hg-bac-2021-lang-p1.json   (مرّة واحدة)
(ثمّ p2 بالطريقة نفسها). لا شكل يُقصّ من ورقة الموضوع (p2-d6 رسم الإجابة النموذجيّة من ملفّ التصحيح، لا يحيل إليه سؤال فلا يُعرض).

ما رُوجع قبل البناء:
- ورقة الموضوع صور ممسوحة بلا طبقة نصّ (pdffonts فارغ، 144 نقطة/بوصة)، وطبقة نصّ التصحيح مشوّهة الترميز: record_wordcheck.py يعلّم
  كلّ الكلمات، فقوبل كلّ سطر من الأسئلة والوثائق وكلّ رقم فيها بصورة الصفحة (300 نقطة/بوصة، وصورة الصفحة الأصلية مكبّرة بلا
  تنعيم عند الشكّ). الجداول والأرقام والمراجع مطابقة؛ الفروق المؤكَّدة في FIXES (منها اسم «جون كنيدي» كما في الورقة، و«كمية الانتاج»
  بلا همزة في خانة الجدول، و«الاتحاد الأوربي» في رأس جدول الموضوع 2).
- الأجوبة الرسميّة للعناصر التفاعليّة قوبلت بصور التصحيح (ص1، 2، 4، 5، 6).

قرارات المحوِّل:
- المصطلحات: mcq، المشتّتات تعريفات مصطلحات أخرى من تصحيح الورقة نفسها (الموضوعان)، تاريخ مع تاريخ وجغرافيا مع جغرافيا. لم يُجمع
  «المحافل الدّولية» مع «منظّمة الأمم المتحدة» (تعريف المحافل يضرب الأمم المتحدة وحركة عدم الانحياز مثالين لها)، ولا «حركة عدم الانحياز»
  مع «المحافل الدّولية»؛ ولم يوضع تعريف «الانفتاح» (يذكر «الاستثمار الخارجي») مشتّتًا لـ«الاستثمار».
- الشخصيّات: ثلاث فقط في التصحيح كلّه (كنيدي، بومدين، غورباتشوف)، وdefinition_step يشترط ثلاثة مشتّتات: person3() المحلّي يبني
  mcq بثلاثة خيارات (التعريف الصحيح + تعريفا الشخصيّتين الأخريين)، بالقاعدة نفسها (split_definition، الاسم كما في الورقة).
- «أكمل الجدول» (الموضوع 1): الأسطر الثلاثة تفاعليّة؛ المشتّتات أحداث/تواريخ من التصحيح غير مطبوعة في الجدول وبصيغة الجواب نفسها.
- مؤجَّل بقرار المحوِّل:
  * «القطبان»: تعريف التصحيح مختلّ الصياغة («مصطلح سياسي والعسكري… هما الوم ا والاس»)، ونقل السجلّ غيّره («العظيمتين»، «ولاس»)،
    وFIXES لا تصل إلى official_answer؛ لا يُعرض خيارًا صحيحًا مختلًّا.
  * التعليق على جدول إنتاج القمح: ست عبارات (comment_step يقبل خمسًا على الأكثر)، وإحداها «ضخامة كمية إنتاج القمح للدّول الواردة في
    الجدول (682.5 م/طن» بينما مجموع الجدول المطبوع 482.7 (133.5+99.7+73.6+52.2+32.3+29.1+24.3+19.5+18.5): لا نجعل خطأ التصحيح جوابًا صحيحًا.
  * «الدّيون»: تعريف التصحيح يسمّي البند («وتتحول الدّيون إلى وسيلة ضغط») فيدلّ على الجواب، ولا مشتّت يحمل الاسم.
- الأعمدة البيانيّة والمقالات: مؤجّلة آليًّا (source_record.py).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from hg_record import definition_step, elements, record_path, refs_for, split_definition, table_step  # noqa: E402
from source_record import build, load, mcq  # noqa: E402

NAME = 'hist-bac-2021-lang.json'
OUT = sys.argv[1]
PDF = sys.argv[sys.argv.index('--pdf') + 1] if '--pdf' in sys.argv else None
REC = load(record_path(NAME))

FIXES = [
    ('p1-d1', 'الصراعات.".', 'الصراعات."'),
    ('p1-d4', 'يسجل', 'يُسجل'),
    ('p1-q5', 'يمثل', 'يمثّل'),
    ('p1-d5', 'كمية الإنتاج', 'كمية الانتاج'),
    ('p1-d7', 'التكتل', 'التّكتل'),
    ('p1-d7', 'جعْله', 'جَعْلِهِ'),
    ('p1-q6', 'التكتل', 'التّكتل'),
    ('p2-d1', '"...إنّ', '"... إنّ'),
    ('p2-d1', 'أيدت', 'أيّدت'),
    ('p2-d1', 'المحافل الدّولية', 'المحافل الدولية'),
    ('p2-q2', 'جون كندي', 'جون كنيدي'),
    ('p2-d2', 'أثّر', 'أثر'),
    ('p2-d3', '"...إنّ', '"... إنّ'),
    ('p2-d4', 'الاتحاد الأوروبي', 'الاتحاد الأوربي'),
    ('p2-d7', 'يطلق', 'يُطلق'),
    ('p2-d7', 'نعمة', 'نِعمة'),
    ('p2-d7', 'ونقمة', 'ونِقمة'),
]

d = lambda eid, ds, skill, kind, name=None: [definition_step(REC, eid, ds, skill, kind, name)]


def person3(eid: str, others: list[str], name: str | None = None) -> list[dict]:
    """definition_step للشخصيّات بمشتّتين (لا شخصيّة ثالثة أخرى في التصحيح): mcq بثلاثة خيارات."""
    E = elements(REC)
    e = E[eid]
    assert e['answer_type'] == 'fixed' and len(others) == 2 and eid not in others, eid
    corr_name, right = split_definition(e['official_answer'])
    name = name or corr_name
    opts = [right] + [split_definition(E[o]['official_answer'])[1] for o in others]
    assert all(opts) and len(set(opts)) == 3, eid
    return [mcq(f'من هو {name}؟', opts, 0, f'«{name}» في الإجابة النموذجيّة: {right}.', e['marks'], 'hist.figures')]


INTERACTIVE = {
    # ── الموضوع الأوّل ──
    'p1-q1-e1': d('p1-q1-e1', ['p1-q1-e2', 'p2-q1-e1', 'p2-q1-e3'], 'hist.terms', 'term', 'الانفراج الدولي'),
    'p1-q1-e2': d('p1-q1-e2', ['p1-q1-e1', 'p2-q1-e1', 'p2-q1-e3'], 'hist.terms', 'term', 'منظمة الأمم المتحدة'),
    'p1-q2-e1': [table_step(REC, 'p1-q2-e1', ['تأسيس حلف وارسو', 'اختطاف طائرة الوفد الخارجي', 'قمع مظاهرات المهاجرين الجزائريين في فرنسا'], asks='event')],
    'p1-q2-e2': [table_step(REC, 'p1-q2-e2', ['1945/10/24', '1961/10/17', '1956/12/26'])],
    'p1-q2-e3': [table_step(REC, 'p1-q2-e3', ['1961/06/30', '1956/12/26', '1961/10/17'])],
    'p1-q4-e1': d('p1-q4-e1', ['p1-q4-e3', 'p2-q4-e2', 'p2-q4-e3'], 'geo.terms', 'term'),
    'p1-q4-e2': d('p1-q4-e2', ['p1-q4-e3', 'p2-q4-e1', 'p2-q4-e3'], 'geo.terms', 'term'),
    'p1-q4-e3': d('p1-q4-e3', ['p1-q4-e1', 'p2-q4-e3', 'p2-q4-e2'], 'geo.terms', 'term'),
    # ── الموضوع الثاني ──
    'p2-q1-e1': d('p2-q1-e1', ['p2-q1-e2', 'p2-q1-e3', 'p1-q1-e1'], 'hist.terms', 'term'),
    'p2-q1-e2': d('p2-q1-e2', ['p2-q1-e1', 'p1-q1-e1', 'p2-q1-e3'], 'hist.terms', 'term', 'المحافل الدولية'),
    'p2-q1-e3': d('p2-q1-e3', ['p2-q1-e1', 'p1-q1-e1', 'p1-q1-e2'], 'hist.terms', 'term'),
    'p2-q2-e1': person3('p2-q2-e1', ['p2-q2-e2', 'p2-q2-e3'], 'جون كنيدي'),
    'p2-q2-e2': person3('p2-q2-e2', ['p2-q2-e1', 'p2-q2-e3']),
    'p2-q2-e3': person3('p2-q2-e3', ['p2-q2-e1', 'p2-q2-e2']),
    'p2-q4-e1': d('p2-q4-e1', ['p2-q4-e2', 'p2-q4-e3', 'p1-q4-e2'], 'geo.terms', 'term'),
    'p2-q4-e3': d('p2-q4-e3', ['p2-q4-e1', 'p2-q4-e2', 'p1-q4-e1'], 'geo.terms', 'term', 'التجارة الدولية'),
}
DEFER = {'p1-q1-e3', 'p1-q5-e1'}
FIGURES: dict = {}
NOTE = ('ورقة الموضوع صور بلا طبقة نصّ: قوبل النقل كلّه بصورة الصفحة. '
        'مؤجَّل بقرار المحوِّل: «القطبان» (تعريف التصحيح مختلّ الصياغة «هما الوم ا والاس»، ونقله في السجلّ مختلف)؛ '
        'التعليق على جدول القمح (ست عبارات، وإحداها تجعل مجموع الجدول 682.5 م/طن والمطبوع يجمع 482.7)؛ '
        '«الدّيون» يسمّي البند في تعريفه: حُذفت من الخيار الصحيح وحده جملة «وتتحول الدّيون إلى وسيلة ضغط…». الشخصيّات ثلاث فقط في التصحيح: mcq بثلاثة خيارات. '
        'اسم الشخصيّة في السؤال كما في ورقة الموضوع («جون كنيدي»).')

# توحيد مع بقيّة المجموعات: عبارة تسمّي البند داخل تعريفه تُحذف من الخيار الصحيح وحده (drop)، ويبقى التعريف كاملًا في الشرح
INTERACTIVE['p2-q4-e2'] = [definition_step(REC, 'p2-q4-e2', ['p2-q4-e1', 'p2-q4-e3', 'p1-q4-e3'], 'geo.terms', 'term', drop=[' وتتحول الدّيون إلى وسيلة ضغط تمارسها الدّول المتقدمة على الدّول المتخلفة'])]

paper = 1 if OUT.endswith('-p1.json') else 2
mine = {k: v for k, v in INTERACTIVE.items() if k.startswith(f'p{paper}-')}
doc = build(record_path(NAME), OUT, interactive=mine, refs=refs_for(NAME), defer=DEFER, pdf=PDF, fixes=FIXES, note=NOTE, figures=FIGURES)
inter = [s for s in doc['steps'] if s['review_status'] == 'needs_human_review']
print(doc['set_id'], len(doc['original_questions']), 'questions', len(doc['steps']), 'steps',
      f"({len(inter)} interactive = {sum(s['points'] for s in inter)} pts)")
