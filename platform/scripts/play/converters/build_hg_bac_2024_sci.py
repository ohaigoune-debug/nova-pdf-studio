def term_mcq(qid, eid, term, pool, distractors, pts, skill):
    assert term not in distractors and len(distractors) == 3 and all(d in pool for d in distractors)
    st(sid(), qid, eid, "mcq", f"ما المقصود بـ«{term}»؟", {"options": [pool[term]] + [pool[d] for d in distractors]}, {"correct": 0},
       f"«{term}» في الإجابة النموذجيّة: {pool[term]}.", pts, skill)


def mcq(qid, eid, prompt, right, wrongs, expl, pts, skill):
    assert len(wrongs) in (2, 3)
    st(sid(), qid, eid, "mcq", prompt, {"options": [right] + list(wrongs)}, {"correct": 0}, expl, pts, skill)


def essay(qid, title, task, para_doc, lines, skill):
    """lines: (eid, section, criterion, indicator_from_correction, points)"""
    for eid, section, crit, ind, pts in lines:
        deferred(sid(), qid, eid, "essay_builder", f"{title} — {section}: {crit}",
                 {"task": task, "paragraph_doc": para_doc, "section": section, "criterion": crit, "indicator": ind},
                 {"rubric": ind, "points": pts, "model_ref": CORR_SHORT},
                 f"سلّم التنقيط ({section}): {ind} — {pts} ن.", pts, skill)


def essay_q(qid, part, verbatim, para_id, para_caption, para, title, task, intro, s1, b1, s2, b2, concl, skill):
    """b1/b2: list of (indicator, points); the criterion is the indicator's head (before «:» or «(»)."""
    def head(t):
        return re.split(r"[:(]", t)[0].strip().rstrip(".").strip() or t
    lines = [(f"{qid}-e1", "المقدمة", "الإشكاليّة", intro, 0.5)]
    k = 1
    for sec, body in ((f"العرض 1- {s1}", b1), (f"العرض 2- {s2}", b2)):
        for ind, pts in body:
            k += 1
            lines.append((f"{qid}-e{k}", sec, head(ind), ind, pts))
    lines.append((f"{qid}-e{k + 1}", "الخاتمة", "الاستنتاج", concl, 0.5))
    q(qid, "—", part, verbatim, 4, [el(e, f"{sec}: {crit}" if sec.startswith("العرض") else sec, pts) for e, sec, crit, _, pts in lines],
      [{"id": para_id, "kind": "text", "caption": para_caption, "text": para}])
    essay(qid, title, task, para_id, lines, skill)


